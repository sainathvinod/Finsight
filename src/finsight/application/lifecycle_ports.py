# Application-facing lifecycle persistence PORTS (ADR-011/012/014/015). Protocol interfaces only —
# the application depends on these, infrastructure (infrastructure/lifecycle_repositories.py) provides
# the SQLite adapters via composition. Pure: no sqlite3, no PySide6, no AI, no I/O.
#
# These declare persistence PRIMITIVES only. They deliberately do NOT include business workflows
# (promotion, supersession-at-promotion, generation creation from verification): those are later-phase
# application services that COMPOSE these primitives inside one UnitOfWork transaction (Phase 6.4c+).
from __future__ import annotations
from typing import List, Optional, Protocol

from finsight.domain.lifecycle import (
    SourceBinding, ReviewGeneration, GenerationSupersession, ExportArtifact,
    IntakeStage, CycleDisposition,
)


class SourceBindingPort(Protocol):
    def upsert(self, binding: SourceBinding) -> None: ...
    def get(self, cycle_id: str, document_type: str) -> Optional[SourceBinding]: ...
    def list_for_cycle(self, cycle_id: str) -> List[SourceBinding]: ...


class ReviewGenerationPort(Protocol):
    def insert(self, generation: ReviewGeneration) -> None: ...
    def get(self, generation_id: str) -> Optional[ReviewGeneration]: ...
    def list_for_cycle(self, cycle_id: str) -> List[ReviewGeneration]: ...
    def next_sequence_number(self, cycle_id: str) -> int: ...
    def working_generation(self, cycle_id: str) -> Optional[ReviewGeneration]: ...
    def published_generation(self, cycle_id: str) -> Optional[ReviewGeneration]: ...


class GenerationSupersessionPort(Protocol):
    """Append-only. There is intentionally no update or delete method."""
    def append(self, supersession: GenerationSupersession) -> None: ...
    def get_successor(self, prior_generation_id: str) -> Optional[GenerationSupersession]: ...
    def history_for_cycle(self, cycle_id: str) -> List[GenerationSupersession]: ...


class ExportArtifactPort(Protocol):
    """Append-only. Export identity is immutable; there is no overwrite method."""
    def insert(self, artifact: ExportArtifact) -> None: ...
    def get(self, export_id: str) -> Optional[ExportArtifact]: ...
    def list_for_generation(self, generation_id: str) -> List[ExportArtifact]: ...
    def list_for_cycle(self, cycle_id: str) -> List[ExportArtifact]: ...


class CycleLifecyclePort(Protocol):
    """Cycle-level lifecycle pointers/stage. These are primitives; moving a pointer is composed with
    supersession + audit inside a single transaction by a later application service (not here)."""
    def set_working_generation(self, cycle_id: str, generation_id: Optional[str]) -> None: ...
    def set_published_generation(self, cycle_id: str, generation_id: Optional[str]) -> None: ...
    def set_intake_stage(self, cycle_id: str, stage: IntakeStage) -> None: ...
    def set_disposition(self, cycle_id: str, disposition: CycleDisposition) -> None: ...
