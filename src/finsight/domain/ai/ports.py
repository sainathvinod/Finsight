# AI Platform port interfaces (Protocols). Framework-independent. Persistence adapters live in
# infrastructure/ai; the grounding adapter composes the deterministic read-model query services.
# The application layer depends only on these interfaces — never on repositories, SQL, or the
# deterministic engine.
from __future__ import annotations
from typing import List, Optional, Protocol
from finsight.domain.ai.contracts import (
    Conversation, ConversationMessage, ReviewMemoryEntry, UserPreference, AiInteractionEntry,
    GroundedReview, GroundedFinding, GroundedSummary, GroundedRuleRun, GroundedProvenanceItem,
    GroundedAuditEvent, AiGroundingContext,
    PromptRequest, ProviderConfiguration, RawProviderResponse,
)


class ConversationRepositoryPort(Protocol):
    def save(self, conversation: Conversation) -> None: ...
    def get(self, conversation_id: str) -> Optional[Conversation]: ...
    def list_for_scope(self, user_id: str, cycle_id: str) -> List[Conversation]: ...
    def update_title(self, conversation_id: str, title: str, updated_ts: str) -> None: ...
    def touch(self, conversation_id: str, updated_ts: str) -> None: ...
    def delete(self, conversation_id: str) -> None: ...   # messages cascade (FK ON DELETE CASCADE)


class MessageRepositoryPort(Protocol):
    def append(self, message: ConversationMessage) -> None: ...
    def list_for_conversation(self, conversation_id: str) -> List[ConversationMessage]: ...
    def next_seq(self, conversation_id: str) -> int: ...
    def clear(self, conversation_id: str) -> None: ...    # delete messages, keep the conversation


class ReviewMemoryRepositoryPort(Protocol):
    def add(self, entry: ReviewMemoryEntry) -> None: ...
    def get(self, memory_id: str) -> Optional[ReviewMemoryEntry]: ...
    def list_for_scope(self, user_id: str, cycle_id: str) -> List[ReviewMemoryEntry]: ...
    def delete(self, memory_id: str) -> None: ...
    def delete_for_scope(self, user_id: str, cycle_id: str) -> int: ...   # returns rows removed


class UserPreferencesRepositoryPort(Protocol):
    def get(self, user_id: str, key: str) -> Optional[UserPreference]: ...
    def set(self, preference: UserPreference) -> None: ...
    def delete(self, user_id: str, key: str) -> None: ...
    def list_for_user(self, user_id: str) -> List[UserPreference]: ...


class AiInteractionJournalPort(Protocol):
    """Append + read only. There is intentionally NO update and NO delete. Operational traceability,
    distinct from the deterministic financial audit trail and from application diagnostic logs.
    Not cryptographically tamper-evident."""
    def append(self, entry: AiInteractionEntry) -> None: ...
    def list_for_scope(self, user_id: str, cycle_id: str) -> List[AiInteractionEntry]: ...


class AiGroundingQueryPort(Protocol):
    """Read-only, review-scoped, structured deterministic facts for the AI platform. Every method
    requires an explicit cycle_id. No raw repositories, SQL, filesystem, or command access."""
    def review(self, cycle_id: str) -> Optional[GroundedReview]: ...
    def findings(self, cycle_id: str) -> List[GroundedFinding]: ...
    def summary(self, cycle_id: str) -> Optional[GroundedSummary]: ...
    def rule_run(self, cycle_id: str) -> Optional[GroundedRuleRun]: ...
    def provenance(self, cycle_id: str) -> List[GroundedProvenanceItem]: ...
    def audit_events(self, cycle_id: str) -> List[GroundedAuditEvent]: ...
    def context(self, cycle_id: str) -> AiGroundingContext: ...


class AiProviderPort(Protocol):
    """A pluggable AI text generator (Phase 4C). Implementations live in infrastructure/ai/providers.
    The application layer depends only on this Protocol and never constructs a provider — composition
    selects one (Ollama when reachable, else NullProvider). Providers must not persist prompts or
    responses, and must never author findings, severity, approvals, or financial actions."""
    def available(self) -> bool: ...
    def generate(self, request: PromptRequest, config: ProviderConfiguration) -> RawProviderResponse: ...
